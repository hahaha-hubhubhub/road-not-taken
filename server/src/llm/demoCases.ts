/** 根据输入稳定挑选一个演示案例（同一输入总是同一案例） */
export function pickDemoCase(input: string): DemoCase {
  let h = 0;
  for (const ch of input) h = (h * 31 + ch.codePointAt(0)!) % 100000;
  return DEMO_CASES[h % DEMO_CASES.length]!;
}
